"""Cached skylines (nominal + PGDA 78 clones) with the exact bundle settings, so several limit
items can share them. Cache under data/cache/science_limits/ (git-ignored; derived from NASA
rasters, regenerated by this module). Heights are float64 (ArrayDEM casts on load)."""
from __future__ import annotations

import json

import numpy as np

from .. import frames, sites
from ..skyline import compute_skyline
from .common import SKY_CACHE

_FAR = {}


def far(site):
    if site not in _FAR:
        _FAR[site] = sites.far_dem(site)
    return _FAR[site]


def skyline(site, clone=None, bins=720, step_m=1.0, max_range_m=280_000.0, near_range_m=None,
            mast_m=1.0, far_dem=None, near_dem=None, tag=None, use_cache=True):
    """clone=None -> nominal PGDA 78 surf tile; int -> PGDA 78 clone k. Observer ground height is
    re-sampled from the near DEM actually used (as in science/margins.py)."""
    key = tag or f'{site}_{"nom" if clone is None else f"c{clone:02d}"}_b{bins}_s{step_m}_r{int(max_range_m)}' \
                 f'_n{near_range_m}_m{mast_m}'
    p = SKY_CACHE / f'{key}.json'
    if use_cache and p.exists():
        return json.loads(p.read_text())
    s = sites.SITES[site]
    nd = near_dem if near_dem is not None else sites.near_dem(site, clone=clone)
    fd = far_dem if far_dem is not None else far(site)
    x, y = frames.stereo_forward(s['lat'], s['lon'])
    h = float(nd.sample(x, y))
    sky = compute_skyline(s['lat'], s['lon'], h, mast_m, near=nd, far=fd, bins=bins,
                          max_range_m=max_range_m, step_m=step_m, near_range_m=near_range_m)
    keep = {k: sky[k] for k in ('bins', 'azimuth_deg', 'elevation_deg', 'status', 'n_truncated', 'max_range_m',
                                'near_cut_m', 'step_near_m', 'step_far_m', 'critical')}
    keep['ground_m'] = h
    keep['near_name'] = nd.name
    if use_cache:
        SKY_CACHE.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(keep))
    return keep


def clone_skylines(site, clones=range(1, 21), **kw):
    return {c: skyline(site, clone=c, **kw) for c in clones}
