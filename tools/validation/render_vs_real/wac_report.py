def _load(d):
    s = [json.loads(l) for l in (d / 'scores.jsonl').read_text().splitlines() if l.strip()] if (d / 'scores.jsonl').exists() else []
    g = list(csv.DictReader(open(d / 'geometry.csv'))) if (d / 'geometry.csv').exists() else []
