"""Render twin of one real LROC NAC image window, inside Blender (Cycles CPU, OSL push-broom camera).

    blender -b --factory-startup --python-exit-code 1 -P tools/validation/render_vs_real/blender_twin.py -- \
        --geometry <geom.json> --osl <camera.osl> --products pgda78_5m,flat --out <dir> [--spp 32]

Scene = the blender/v2 builder's pieces: blender/v2/terrain.py (levels, view-dependent tiles, grid -> ENU with curvature),
blender/v2/hapke_nodes.py (Hapke 2012 regolith, LROC WAC 643 nm parameters, SOUTH_60_70), a SUN lamp with the true angular
diameter and 1361 W m^-2 / r_au^2 irradiance (Kopp & Lean 2011), black airless world. Camera = the per-image OSL push-broom
generated by nac_camera.osl_source (raster v = 1 is the first cropped image line).

Per terrain product, four renders on the binned image grid (top-down arrays saved to <out>/<product>.npz):
  beauty   Hapke material, Sun disc, bounces, BOX filter 1 px, `spp` samples  -> radiance (W m^-2 sr^-1), alpha
  lit      white diffuse, flat shading, Sun angle 0 (Sun CENTRE), direct only, 1 sample, filter 0.01 px -> lit > 0
           (protocol §4.1: shadow iff the ray to the Sun centre is blocked or local incidence >= 90 deg)
  pos      emission = surface position (ENU m) + 1e5, 1 sample, filter 0.01 px
  nrm      emission = true (geometric) normal * 0.5 + 0.5
Labels: terrain SOURCE-BASED · UNVALIDATED; photometry MODEL.
"""
import argparse
import json
import math
import os
import sys
import time
from pathlib import Path

import bpy
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / 'blender'))
from v2 import hapke, hapke_nodes, terrain as T  # noqa: E402

TSI_W_M2 = 1361.0
AU_M = 149_597_870_700.0
R_SUN_M = 695_700_000.0           # IAU 2015 nominal solar radius
POS_OFFSET = 1.0e5
WORK = Path(os.environ.get('POLARIS_DATA', ROOT / 'data' / 'cache')) / 'v2' / 'render_vs_real'


def args():
    ap = argparse.ArgumentParser()
    ap.add_argument('--geometry', required=True)
    ap.add_argument('--osl', required=True)
    ap.add_argument('--products', default='pgda78_5m,lola_ldem875s_5m,pgda90_80m,flat')
    ap.add_argument('--out', required=True)
    ap.add_argument('--spp', type=int, default=32)
    ap.add_argument('--bounces', type=int, default=4)
    ap.add_argument('--budget', type=int, default=8_000_000)
    ap.add_argument('--threads', type=int, default=4)
    ap.add_argument('--photometry', default='hapke')
    ap.add_argument('--beauty-only', action='store_true', help='skip the geometry passes (photometry variants)')
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    return ap.parse_args(argv)


def level_from_npz(path, name):
    z = np.load(path)
    meta = json.loads(str(z['meta']))
    return T.Level(name=name, h=np.ascontiguousarray(z['h']), x0=float(z['x0']), y0=float(z['y0']), step=float(z['step']),
                   source=meta.get('source', ''), sha256=meta.get('sha256', ''), info={'product': meta.get('product')})


def reset_scene():
    for o in list(bpy.data.objects):
        bpy.data.objects.remove(o, do_unlink=True)
    for m in list(bpy.data.meshes):
        bpy.data.meshes.remove(m)


def mesh_object(name, V, F, mat):
    me = bpy.data.meshes.new(name)
    V = np.asarray(V, dtype=np.float32)
    F = np.asarray(F, dtype=np.int32)
    me.vertices.add(len(V))
    me.vertices.foreach_set('co', V.ravel())
    me.loops.add(F.size)
    me.loops.foreach_set('vertex_index', F.ravel())
    me.polygons.add(len(F))
    me.polygons.foreach_set('loop_start', np.arange(0, F.size, F.shape[1], dtype=np.int32))
    me.update(calc_edges=True)
    ob = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(ob)
    me.materials.append(mat)
    return ob


def set_smooth(objs, smooth):
    for ob in objs:
        n = len(ob.data.polygons)
        ob.data.polygons.foreach_set('use_smooth', np.full(n, smooth, dtype=bool))
        ob.data.update()


def node_mat(name, kind):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    for n in list(nt.nodes):
        nt.nodes.remove(n)
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    if kind == 'white':
        d = nt.nodes.new('ShaderNodeBsdfDiffuse')
        d.inputs['Color'].default_value = (1, 1, 1, 1)
        d.inputs['Roughness'].default_value = 0.0
        nt.links.new(d.outputs[0], out.inputs['Surface'])
        return m
    g = nt.nodes.new('ShaderNodeNewGeometry')
    em = nt.nodes.new('ShaderNodeEmission')
    vm = nt.nodes.new('ShaderNodeVectorMath')
    if kind == 'pos':
        vm.operation = 'ADD'
        vm.inputs[1].default_value = (POS_OFFSET, POS_OFFSET, POS_OFFSET)
        nt.links.new(g.outputs['Position'], vm.inputs[0])
    else:
        vm.operation = 'MULTIPLY_ADD'
        vm.inputs[1].default_value = (0.5, 0.5, 0.5)
        vm.inputs[2].default_value = (0.5, 0.5, 0.5)
        nt.links.new(g.outputs['True Normal'], vm.inputs[0])
    nt.links.new(vm.outputs[0], em.inputs['Color'])
    nt.links.new(em.outputs[0], out.inputs['Surface'])
    return m


def lunar_lambert_mat(name, light_dir, L):
    """McEwen (1991) lunar-Lambert: r = (A/pi) [2L mu0/(mu0+mu) + (1-L) mu0]; colour = pi r / mu0 (A = 1, scale-free:
    the exposure normalisation removes the albedo)."""
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    for n in list(nt.nodes):
        nt.nodes.remove(n)
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    d = nt.nodes.new('ShaderNodeBsdfDiffuse')
    g = nt.nodes.new('ShaderNodeNewGeometry')
    Lv = nt.nodes.new('ShaderNodeCombineXYZ')
    for i, c in enumerate(light_dir):
        Lv.inputs[i].default_value = float(c)

    def vm(op, a, b):
        n = nt.nodes.new('ShaderNodeVectorMath')
        n.operation = op
        nt.links.new(a, n.inputs[0])
        nt.links.new(b, n.inputs[1])
        return n.outputs['Value']

    def math_(op, a, b, clamp=False):
        n = nt.nodes.new('ShaderNodeMath')
        n.operation = op
        n.use_clamp = clamp
        for k, v in enumerate((a, b)):
            if isinstance(v, (int, float)):
                n.inputs[k].default_value = float(v)
            else:
                nt.links.new(v, n.inputs[k])
        return n.outputs[0]
    mu0 = math_('MAXIMUM', vm('DOT_PRODUCT', g.outputs['Normal'], Lv.outputs[0]), 1e-4)
    mu = math_('MAXIMUM', vm('DOT_PRODUCT', g.outputs['Normal'], g.outputs['Incoming']), 1e-4)
    term = math_('DIVIDE', 2.0 * L, math_('ADD', mu0, mu))             # 2L/(mu0+mu)  (= pi r / mu0 minus the Lambert part)
    col = math_('MINIMUM', math_('ADD', term, 1.0 - L), 4.0)
    nt.links.new(col, d.inputs['Color'])
    nt.links.new(d.outputs[0], out.inputs['Surface'])
    return m


def render_to_array(path):
    bpy.context.scene.render.filepath = str(path)
    bpy.ops.render.render(write_still=True)
    im = bpy.data.images.load(str(path))
    w, h = im.size
    a = np.array(im.pixels[:], dtype=np.float32).reshape(h, w, 4)[::-1]
    bpy.data.images.remove(im)
    os.remove(path)
    return a


def main():
    a = args()
    G = json.loads(Path(a.geometry).read_text())
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    reset_scene()
    sc = bpy.context.scene
    sc.render.engine = 'CYCLES'
    cy = sc.cycles
    cy.device = 'CPU'
    cy.shading_system = True                 # OSL: needed by the custom camera
    sc.render.threads_mode = 'FIXED'
    sc.render.threads = a.threads
    cy.use_denoising = False
    cy.use_adaptive_sampling = False
    cy.seed = 0
    sc.render.film_transparent = True
    sc.render.resolution_x = int(G['render_w'])
    sc.render.resolution_y = int(G['render_h'])
    sc.render.resolution_percentage = 100
    sc.view_settings.view_transform = 'Raw'
    sc.view_settings.look = 'None'
    sc.view_settings.exposure = 0.0
    sc.view_settings.gamma = 1.0
    sc.render.image_settings.file_format = 'OPEN_EXR'
    sc.render.image_settings.color_depth = '32'
    sc.render.image_settings.color_mode = 'RGBA'
    sc.render.use_persistent_data = True
    world = bpy.data.worlds.new('airless')
    world.use_nodes = True
    world.node_tree.nodes['Background'].inputs['Strength'].default_value = 0.0
    sc.world = world

    txt = bpy.data.texts.new('pushbroom.osl')
    txt.write(Path(a.osl).read_text())
    cd = bpy.data.cameras.new('pushbroom')
    cd.type = 'CUSTOM'
    cd.custom_mode = 'INTERNAL'
    cd.custom_shader = txt
    cd.clip_start = 1.0
    cd.clip_end = 5.0e6                    # default 100 m would clip every ray from orbit
    co = bpy.data.objects.new('pushbroom', cd)
    sc.collection.objects.link(co)
    sc.camera = co

    sun = np.asarray(G['sunEnu'], float)
    sun /= np.linalg.norm(sun)
    dist = float(G['sunDistM'])
    ld = bpy.data.lights.new('Sun', type='SUN')
    ld.energy = TSI_W_M2 / (dist / AU_M) ** 2
    sun_angle = 2.0 * math.asin(R_SUN_M / dist)
    ld.angle = sun_angle
    lo = bpy.data.objects.new('Sun', ld)
    sc.collection.objects.link(lo)
    from mathutils import Vector
    lo.rotation_mode = 'QUATERNION'
    lo.rotation_quaternion = Vector(sun.tolist()).to_track_quat('Z', 'Y')

    frame = T.EnuFrame(G['enu']['lat'], G['enu']['lon'], G['enu']['h0'])
    Rmid = np.asarray(G['fit']['Rmid'])
    fwd = Rmid @ np.array([0.0, 0.0, 1.0])
    pos = np.asarray(G['scPosEnuMid'])
    rng = float(np.linalg.norm(pos))
    ifov = 10.0054e-6 * G['summing'] * G['bin']
    # View cone for the builder's tile planner: it must contain every ground point the moving push-broom sees, so it is
    # sized from the fitted rays at the strip's corners and edge midpoints (sphere R + h0), plus 0.03 rad.
    sys.path.insert(0, str(ROOT))
    from tools.validation.render_vs_real.nac_camera import eval_states
    ns, csum, b = G['label']['samples'], G['summing'], G['bin']
    ll = np.array([G['l0'], G['l0'], (G['l0'] + G['l1']) / 2, G['l1'], G['l1'], (G['l0'] + G['l1']) / 2])
    ss = np.array([0.5, ns + 0.5, 0.5, 0.5, ns + 0.5, ns + 0.5])
    Pp, Rr = eval_states(G['fit'], ll)
    det = (ss - 1.0) * csum + csum / 2.0 + 0.5
    from tools.validation.render_vs_real.nac_camera import IK
    ik = IK[G['frame']]
    yy = ik['transy'] * (det - ik['boresight'])
    yy = yy / (1 + ik['od_k'] * yy * yy)
    lc = np.stack([np.zeros_like(yy), yy, np.full_like(yy, ik['focal_mm'])], 1)
    lc /= np.linalg.norm(lc, axis=1, keepdims=True)
    dd = np.einsum('nij,nj->ni', Rr, lc)
    C = np.array([0.0, 0.0, -(6378.0 * 0 + 1_737_400.0 + G['enu']['h0'])])
    oc = Pp - C
    bq = np.einsum('ij,ij->i', oc, dd)
    tt = -bq - np.sqrt(np.maximum(bq * bq - (np.einsum('ij,ij->i', oc, oc) - (1_737_400.0 + G['heightRange'][0]) ** 2), 0))
    X = Pp + tt[:, None] * dd
    vv = X - pos
    ang = np.arccos(np.clip(vv @ fwd / np.linalg.norm(vv, axis=1), -1, 1))
    cone = float(ang.max()) + 0.03
    half_h = half_v = math.atan(math.tan(cone) / math.sqrt(2))
    view = T.View(pos=tuple(pos), fwd=tuple(fwd), half_h=half_h, half_v=half_v, pixel_rad=ifov,
                  sun_dir=tuple(sun), sun_radius_rad=sun_angle / 2)
    hp = hapke.params('SOUTH_60_70')
    if a.photometry == 'hapke':
        beauty_mat, _info = hapke_nodes.hapke_material('Hapke regolith', hp, tuple(sun))
    elif a.photometry.startswith('lunarlambert'):
        beauty_mat = lunar_lambert_mat('lunar-Lambert', tuple(sun), float(a.photometry.split(':')[1]))
    elif a.photometry == 'lommel':
        beauty_mat = lunar_lambert_mat('Lommel-Seeliger', tuple(sun), 1.0)
    else:
        raise SystemExit(f'unknown photometry {a.photometry}')
    mats = {'white': node_mat('white', 'white'), 'pos': node_mat('pos', 'pos'), 'nrm': node_mat('nrm', 'nrm')}
    site = G['site']
    tdir = WORK / 'terrain'
    log = {'geometry': a.geometry, 'blender': bpy.app.version_string, 'spp': a.spp, 'bounces': a.bounces,
           'sunAngleDeg': math.degrees(sun_angle), 'sunIrradiance': ld.energy, 'photometry': a.photometry, 'products': {}}
    for prod in a.products.split(','):
        t0 = time.time()
        for o in [o for o in bpy.data.objects if o.name.startswith('TERRAIN')]:
            bpy.data.objects.remove(o, do_unlink=True)
        levels = [level_from_npz(tdir / f'{site}__{prod}.npz', f'near {prod}')]
        if prod != 'flat':
            levels.append(level_from_npz(tdir / f'{site}__far_pgda90_80m.npz', 'far PGDA 90 80 m'))
        tiles, rep = T.plan_tiles(levels, frame, view, budget=a.budget)
        objs = []
        for li, lv in enumerate(levels):
            finer = [levels[j].box() for j in range(li)]
            Vs, Fs, base = [], [], 0
            for t in tiles:
                if t['level'] != li:
                    continue
                V, F, _d = T.tile_mesh(lv, t, frame, finer)
                if len(F):
                    Vs.append(V)
                    Fs.append(F + base)
                    base += len(V)
            if Vs:
                objs.append(mesh_object(f'TERRAIN {lv.name}', np.vstack(Vs), np.vstack(Fs), beauty_mat))
        t_build = time.time() - t0
        res = {}
        timings = {}
        # beauty
        for ob in objs:
            ob.data.materials[0] = beauty_mat
        set_smooth(objs, True)
        ld.angle = sun_angle
        cy.samples = a.spp
        cy.max_bounces = a.bounces
        cy.diffuse_bounces = a.bounces
        cy.pixel_filter_type = 'BOX'
        cy.filter_width = 1.0
        t1 = time.time()
        b = render_to_array(out / f'_{prod}_beauty.exr')
        timings['beauty'] = time.time() - t1
        res['beauty'] = b[..., 0]
        res['alpha'] = b[..., 3]
        if a.beauty_only:
            np.savez_compressed(out / f'{prod}__{a.photometry.replace(":", "")}.npz', **res)
            log['products'][prod] = {'buildS': t_build, 'renderS': timings, 'beautyOnly': True}
            print(f'[R4 twin] {prod} {a.photometry}: build {t_build:.1f}s render {timings}', flush=True)
            continue
        # geometry passes: Sun centre, direct only, flat shading, pixel-centre rays
        set_smooth(objs, False)
        ld.angle = 0.0
        cy.samples = 1
        cy.max_bounces = 0
        cy.diffuse_bounces = 0
        cy.filter_width = 0.01
        for key in ('white', 'pos', 'nrm'):
            for ob in objs:
                ob.data.materials[0] = mats[key]
            t1 = time.time()
            g = render_to_array(out / f'_{prod}_{key}.exr')
            timings[key] = time.time() - t1
            if key == 'white':
                res['lit'] = g[..., 0] > 0.0
                res['hit'] = g[..., 3] > 0.5
            elif key == 'pos':
                res['pos'] = np.where(g[..., 3:4] > 0.5, g[..., :3] - POS_OFFSET, np.nan).astype(np.float32)
            else:
                res['nrm'] = np.where(g[..., 3:4] > 0.5, g[..., :3] * 2 - 1, np.nan).astype(np.float32)
        np.savez_compressed(out / f'{prod}.npz', **res)
        log['products'][prod] = {'tileReport': {k: v for k, v in rep.items() if k != 'tiles'}, 'buildS': t_build, 'renderS': timings,
                                 'vertices': int(sum(len(o.data.vertices) for o in objs))}
        print(f'[R4 twin] {prod}: build {t_build:.1f}s render {timings}', flush=True)
    (out / f'render_log_{a.photometry.replace(":", "")}.json').write_text(json.dumps(log, indent=1, default=str))


if __name__ == '__main__':
    main()
