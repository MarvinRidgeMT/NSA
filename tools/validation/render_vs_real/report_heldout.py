"""docs/validation/RENDER_VS_REAL_HELDOUT.md from results_heldout/ (Amendment A5). Formatting only: the claim rule and the
near-total-shadow stratum come from the registered heldout.py.

    POLARIS_RVR_SPLIT=heldout python -m tools.validation.render_vs_real.report_heldout [--gallery]
    python -m tools.validation.render_vs_real.report_heldout --out /tmp/x.md     # dry run on the dev records (format check)

--gallery also writes the local (git-ignored) thumbnails to docs/validation/render_vs_real_heldout/: crops of LROC NAC images
(credit NASA/GSFC/Arizona State University), never committed.
"""
from __future__ import annotations

import argparse
import collections
import csv
import hashlib
import json
import math
from pathlib import Path

import numpy as np

from . import common as C, heldout as H
from .report import METRICS, PNAME, PRODUCTS, SITES, boot_ci, fmt, hero, paired, q, table_dist, thumb

DOC = C.ROOT / 'docs' / 'validation' / 'RENDER_VS_REAL_HELDOUT.md'
GAL = C.ROOT / 'docs' / 'validation' / 'render_vs_real_heldout'
DEV_RESULTS = Path(__file__).resolve().parent / 'results'


def _load(d):
    s = [json.loads(l) for l in (d / 'scores.jsonl').read_text().splitlines() if l.strip()] if (d / 'scores.jsonl').exists() else []
    g = list(csv.DictReader(open(d / 'geometry.csv'))) if (d / 'geometry.csv').exists() else []
    sel = json.loads((d / 'selection.json').read_text()) if (d / 'selection.json').exists() else {}
    log = [json.loads(l) for l in (d / 'RUN_LOG.jsonl').read_text().splitlines() if l.strip()] if (d / 'RUN_LOG.jsonl').exists() else []
    return s, g, sel, log


def hl(scores, product='pgda78_5m', phot='hapke', reg=True):
    return H.headline_records(scores, product, phot, reg)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='')
    ap.add_argument('--gallery', action='store_true')
    a = ap.parse_args(argv)
    if C.SPLIT == 'dev' and not a.out:
        raise SystemExit('dev mode only writes a dry run: pass --out (or run with POLARIS_RVR_SPLIT=heldout)')
    scores_all, geo, sel, log = _load(C.RESULTS)
    dev_all, *_ = _load(DEV_RESULTS)
    if not isinstance(sel.get('gatedByMetadata'), list):     # dev selection stores counts, not rows
        sel = {**sel, 'gatedByMetadata': []}
    rows = C.read_catalogue()
    C.assert_dev({r['product_id'] for r in scores_all} | {g['product_id'] for g in geo}, rows)
    cat = {(r['product_id'], r['site']): r for r in rows}
    native = {k: float(r['pixel_scale_m']) for k, r in cat.items() if r['pixel_scale_m']}
    split = 'held-out run' if C.SPLIT == 'heldout' else 'DEV DRY RUN (format check, not a result)'
    rr = hl(scores_all)
    keys = {(r['product_id'], r['site']) for r in rr}
    fdf = [r for r in scores_all if r.get('orbit') == 'fdf']
    failed = [r for r in scores_all if r.get('status') == 'failed']
    gated_score = {(r['product_id'], r['site']): r.get('reason') for r in scores_all
                   if r.get('status') == 'gated' and r.get('product') == 'pgda78_5m' and r.get('photometry') == 'hapke'
                   and r.get('registered')}
    L = []
    w = L.append
    w(f'# Render vs real — LROC NAC, {split} (Amendment A5)\n')
    w(f'**SOURCE-BASED · UNVALIDATED · {split}.** Pre-registered: protocol `docs/v2/RENDER_VS_REAL_PROTOCOL.md` (frozen) + '
      'amendments A1–A5, hashes in `docs/v2/PREREGISTRATION.md` (Entry 6 freezes A5 and the code this run executed). '
      'Generated by `tools/validation/render_vs_real/report_heldout.py` from `results_heldout/`. The claim rule (§2) and the '
      'near-total-shadow stratum (§6) are computed by the registered `heldout.py`; this report only formats them. A good score '
      'validates render geometry only; it does not certify illumination power, DSN or link availability.\n')
    w('Imagery: LROC NAC CDR, NASA PDS (public domain per the LROC terms, https://lroc.im-ldi.com/about/terms). Credit: '
      '**NASA/GSFC/Arizona State University**. SPICE: NAIF PDS `lro-l-spice-6-v1.0`; orbits: LOLA/LRO RS GRGM900C (PDS '
      'Geosciences). Terrain: LOLA (PGDA 78, PGDA 90, PDS LDEM).\n')
    # 1. accounting
    w('## 1. Every held-out row\n')
    starts = [e for e in log if e['event'] == 'start']
    stops = [e for e in log if e['event'] == 'stop']
    if starts:
        w(f"- Run: started {starts[0]['utc']} at commit `{starts[0]['commit'][:10]}`; "
          f"{len(starts)} start(s) (resumptions after the first: {sum(1 for e in starts[1:])}); "
          f"last stop {stops[-1]['utc'] if stops else '— (not finished)'}.")
    gm = collections.Counter(g['reason'] for g in sel.get('gatedByMetadata', []))
    w(f"- Held-out LROC NAC rows in the frozen catalogue: **{sel.get('heldoutRows', '—')}**. Gated by the §2 metadata rules: "
      f"{sum(gm.values())} ({'; '.join(f'{k}: {v}' for k, v in gm.most_common())}). Eligible: {sel.get('nRows', '—')} rows / "
      f"{sel.get('nImages', '—')} images.")
    gs = collections.Counter(g['status'] for g in geo)
    w(f"- Geometry: {gs.get('ok', 0)} OK, {gs.get('gated', 0)} gated, {gs.get('failed', 0)} failed.")
    w(f"- Scored (PGDA 78, Hapke, registered) on the GRGM900C orbit: **{len(keys)} rows** — the headline set. FDF-orbit "
      f"rows: {len({(r['product_id'], r['site']) for r in fdf if r.get('status') == 'scored'})} (§7). Gated at scoring "
      f"(window < 500 px): {len(gated_score)}. Render/score failures: {len({(r['product_id'], r['site']) for r in failed})}.")
    eligible_keys = {(i['product_id'], s) for i in sel.get('images', []) for s in i['sites']}
    accounted = keys | {(r['product_id'], r['site']) for r in scores_all} | {(g['product_id'], g['site']) for g in geo
                                                                               if g['status'] != 'ok'}
    missing = sorted(eligible_keys - accounted)
    w(f"- Eligible rows with no outcome yet: {len(missing)}" + (f" ({', '.join(f'{p} {s}' for p, s in missing[:10])}"
                                                                 f"{' …' if len(missing) > 10 else ''})" if missing else '') + '.\n')
    w('Strata of the scored rows vs all eligible held-out rows:\n')
    for ax in ('site', 'el_bin', 'az_bin', 'em_bin'):
        ce = collections.Counter(cat[k][ax] for k in eligible_keys)
        cs = collections.Counter(cat[k][ax] for k in keys)
        w(f'- **{ax}**: ' + ', '.join(f'{k} {cs.get(k, 0)}/{ce[k]}' for k in sorted(ce)))
    w('')
    # 2. claim rule
    w('## 2. Protocol §8 claim rule, per site (A5.6)\n')
    w('Registered, Hapke, GRGM900C rows. Conditions: (1) median shadow IoU ≥ 0.80; (2) median edge error ≤ 2 × the median '
      'analysis pixel (binned GSD); (3) beats the flat-sphere control on ≥ 80 % of paired images for IoU **and** for edge '
      'error. The native-pixel column is reported, not the rule (A5.6 disclosure).\n')
    for p in ('pgda78_5m', 'lola_ldem875s_5m', 'pgda90_80m'):
        cr = H.claim_rule(scores_all, native, sites=SITES, product=p)
        w(f'### {PNAME[p]}' + (' (headline)' if p == 'pgda78_5m' else '') + '\n')
        w('| site | n | median IoU | median edge m (n) | limit m (2 × analysis px) | within 2 native px | beats control IoU / edge | '
          'claim |')
        w('|---|---|---|---|---|---|---|---|')
        for s in SITES:
            c = cr[s]
            if not c['n']:
                w(f'| {s} | 0 | — | — | — | — | — | no scored rows |')
                continue
            verdict = '**met**' if c['claim'] else 'not met: ' + ', '.join(c['failed'])
            w(f"| {s} | {c['n']} | {fmt(c['medianIouShadow'])} | {fmt(c['medianEdgeM'], 1)} ({c['nEdge']}) | "
              f"{fmt(c['edgeLimitM'], 1)} | {'yes' if c['edgeWithinNative2px'] else 'no'} | "
              f"{c['fracBeatsControlIou']:.0%} / {c['fracBeatsControlEdge']:.0%} | {verdict} |")
        w('')
    w('Where the claim is met, the report may say "renders reproduce observed shadow placement at <site>/LROC NAC" for that '
      'product, and nothing broader: no number here is combined across sites, products or instruments, and none is a '
      'probability.\n')
    # 3. distributions
    w('## 3. Score distributions — PGDA 78 5 m, Hapke, registered (headline)\n')
    w(table_dist(rr))
    w('\nSame, **unregistered**:\n')
    w(table_dist(hl(scores_all, reg=False)))
    w('\n### 3.1 Per site\n')
    w('| site | n | shadow IoU median (IQR) | edge median m (IQR) | SSIM median | W1 median | weak-bimodality rows |')
    w('|---|---|---|---|---|---|---|')
    for s in SITES:
        x = [r for r in rr if r['site'] == s]
        if not x:
            w(f'| {s} | 0 | — | — | — | — | — |')
            continue
        iou, ed = [r['iouShadow'] for r in x], [r['edgeMedianM'] for r in x]
        w(f"| {s} | {len(x)} | {fmt(q(iou, 50))} ({fmt(q(iou, 25))}–{fmt(q(iou, 75))}) | {fmt(q(ed, 50), 1)} "
          f"({fmt(q(ed, 25), 1)}–{fmt(q(ed, 75), 1)}) | {fmt(q([r['ssim'] for r in x], 50))} | "
          f"{fmt(q([r['wasserstein1'] for r in x], 50))} | {sum(r['weakBimodality'] for r in x)} |")
    w('\n### 3.2 By Sun elevation bin (catalogue strata)\n')
    w('| el_bin | n | shadow IoU median | lit IoU median | edge median m | obs. shadow fraction median |\n|---|---|---|---|---|---|')
    byel = collections.defaultdict(list)
    for r in rr:
        byel[cat[(r['product_id'], r['site'])]['el_bin']].append(r)
    for k in sorted(byel):
        x = byel[k]
        w(f"| {k} | {len(x)} | {fmt(q([r['iouShadow'] for r in x], 50))} | {fmt(q([r['iouLit'] for r in x], 50))} | "
          f"{fmt(q([r['edgeMedianM'] for r in x], 50), 1)} | {fmt(q([r['obsShadowFrac'] for r in x], 50))} |")
    # 4. dev vs held-out
    w('\n## 4. Held-out next to dev (PGDA 78, Hapke, registered, GRGM900C rows; dev = the A1–A4 pilot)\n')
    dv = hl(dev_all)
    w('| metric | dev n | dev median | held-out n | held-out median |\n|---|---|---|---|---|')
    for m, name, d in METRICS:
        a_ = [r.get(m) for r in dv]
        b_ = [r.get(m) for r in rr]
        n_ = lambda v: sum(1 for x in v if isinstance(x, (int, float)) and math.isfinite(x))   # noqa: E731
        w(f'| {name} | {n_(a_)} | {fmt(q(a_, 50), d)} | {n_(b_)} | {fmt(q(b_, 50), d)} |')
    # 5. products
    w('\n## 5. Terrain products (paired on the same rows; Hapke, registered, GRGM900C)\n')
    w('| product | n | shadow IoU median | edge median m | edge unmatched | SSIM | W1 |\n|---|---|---|---|---|---|---|')
    for p in PRODUCTS:
        x = hl(scores_all, p)
        w(f"| {PNAME[p]} | {len(x)} | {fmt(q([r['iouShadow'] for r in x], 50))} | {fmt(q([r['edgeMedianM'] for r in x], 50), 1)} | "
          f"{fmt(q([r['edgeUnmatchedFrac'] for r in x], 50))} | {fmt(q([r['ssim'] for r in x], 50))} | "
          f"{fmt(q([r['wasserstein1'] for r in x], 50))} |")
    w('\nPaired per-row differences: median and bootstrap 95 % interval (10,000 resamples of rows, seed `polaris-x-v2-boot`); '
      'descriptive, not a hypothesis test. IoU, SSIM: positive = first better; edge error, W1: negative = first better.\n')
    w('| comparison | metric | n pairs | median diff | 95 % interval | first better in |\n|---|---|---|---|---|---|')
    grg = [r for r in scores_all if r.get('orbit') == 'grgm900c']
    for a_, b_ in (('pgda78_5m', 'flat'), ('pgda78_5m', 'pgda90_80m'), ('pgda78_5m', 'lola_ldem875s_5m'),
                   ('lola_ldem875s_5m', 'flat'), ('pgda90_80m', 'flat')):
        for m, better in (('iouShadow', 1), ('edgeMedianM', -1), ('ssim', 1), ('wasserstein1', -1)):
            d, _k = paired(grg, a_, b_, m)
            if not d:
                continue
            lo, hi = boot_ci(d)
            w(f'| {PNAME[a_]} − {PNAME[b_]} | {m} | {len(d)} | {fmt(float(np.median(d)))} | {fmt(lo)} … {fmt(hi)} | '
              f'{np.mean([(x * better) > 0 for x in d]):.0%} |')
    w('\n## 6. Near-total-shadow windows (A5.5) and weak bimodality\n')
    nts = H.near_total_shadow(scores_all)
    w(f'Stratum: registered PGDA 78 predicted shadow fraction ≥ {H.NEAR_TOTAL_SHADOW}. The headline (§3) includes every row; '
      'this split is reporting only. The count-matched IoU is the A5.5 secondary mask (sensitivity only; never headline, '
      'never in §8; no dev baseline exists).\n')
    w('| stratum | n | Otsu shadow IoU median (IQR) | Otsu lit IoU median | count-matched shadow IoU median | count-matched lit IoU median |')
    w('|---|---|---|---|---|---|')
    for name, x in (('all rows', rr), (f'predicted shadow ≥ {H.NEAR_TOTAL_SHADOW}', [r for r in rr if (r['product_id'], r['site']) in nts]),
                    ('the rest', [r for r in rr if (r['product_id'], r['site']) not in nts])):
        iou = [r['iouShadow'] for r in x]
        w(f"| {name} | {len(x)} | {fmt(q(iou, 50))} ({fmt(q(iou, 25))}–{fmt(q(iou, 75))}) | {fmt(q([r['iouLit'] for r in x], 50))} | "
          f"{fmt(q([r.get('cmIouShadow') for r in x], 50))} | {fmt(q([r.get('cmIouLit') for r in x], 50))} |")
    dn = H.near_total_shadow(dev_all)
    dvi = [r['iouShadow'] for r in dv if (r['product_id'], r['site']) in dn]
    w(f"\nDev, same cut: n = {len(dvi)}, Otsu shadow IoU median {fmt(q(dvi, 50))}. Weak-bimodality rows (held-out): "
      f"{sum(r['weakBimodality'] for r in rr)}; render median zero (A1.4 fallback): {sum(r['renderMedianZero'] for r in rr)} "
      f"of {len(rr)}.\n")
    # registration
    off = [r['regOffsetM'] for r in rr]
    al = [r.get('regOffsetAlongSunM') for r in rr]
    ac = [r.get('regOffsetAcrossSunM') for r in rr]
    w('## 7. Registration and orbit\n')
    w(f"- Offset magnitude (m, GRGM900C rows, search ± 60 m): median {fmt(q(off, 50), 1)}, P90 {fmt(q(off, 90), 1)}, max "
      f"{fmt(max(off) if off else float('nan'), 1)}; at the search bound: {sum(r['regAtBound'] for r in rr)}; beyond 60 m: "
      f"{sum(r.get('offsetBeyondDocumented', False) for r in rr)}. For σ = 20 m per axis a Rayleigh law gives median "
      f"{20 * math.sqrt(2 * math.log(2)):.1f} m, P90 {20 * math.sqrt(2 * math.log(10)):.1f} m.")
    w(f"- Along the Sun azimuth (real − render): median {fmt(q(al, 50), 1)} m (P10 {fmt(q(al, 10), 1)}, P90 {fmt(q(al, 90), 1)}); "
      f"across: median {fmt(q(ac, 50), 1)} m. Per site along-Sun medians: " + '; '.join(
          f"{s} {fmt(q([r.get('regOffsetAlongSunM') for r in rr if r['site'] == s], 50), 1)} "
          f"(n = {sum(1 for r in rr if r['site'] == s)})" for s in SITES) + '. Dev pilot: negative at every site, cause open.')
    fr = [r for r in fdf if r.get('status') == 'scored' and r['product'] == 'pgda78_5m' and r['photometry'] == 'hapke']
    fu = {(r['product_id'], r['site']): r for r in fr if not r['registered']}
    frr = sorted([r for r in fr if r['registered']], key=lambda r: (r['product_id'], r['site']))
    w('\n### 7.1 FDF-orbit rows (no GRGM900C coverage; search ± 400 m; never in the claim)\n')
    if frr:
        w('| product id | site | shadow IoU unreg. | shadow IoU reg. | edge median m reg. | offset m |\n|---|---|---|---|---|---|')
        for r in frr:
            u = fu.get((r['product_id'], r['site']), {})
            w(f"| {r['product_id']} | {r['site']} | {fmt(u.get('iouShadow'))} | {fmt(r['iouShadow'])} | {fmt(r['edgeMedianM'], 1)} | "
              f"{fmt(r['regOffsetM'], 0)} |")
    else:
        w('None scored.')
    # photometry
    w('\n## 8. Photometric models (PGDA 78, registered, GRGM900C)\n')
    w('| photometry | n | SSIM median | W1 median | JSD median | registration NCC median |\n|---|---|---|---|---|---|')
    for ph in ('hapke', 'lunarlambert:0.5', 'lommel'):
        x = hl(scores_all, 'pgda78_5m', ph)
        w(f"| {ph} | {len(x)} | {fmt(q([r['ssim'] for r in x], 50))} | {fmt(q([r['wasserstein1'] for r in x], 50))} | "
          f"{fmt(q([r['jsdBits'] for r in x], 50))} | {fmt(q([r['regNcc'] for r in x], 50))} |")
    # hero
    w('\n## 9. Site04 RoI 3 hero point\n')
    try:
        hp = [h for h in hero(grg) if h.get('inImage')]
    except Exception as e:      # renders not reduced / missing locally
        hp = []
        w(f'Not computed here ({type(e).__name__}: {str(e)[:120]}).\n')
    n04 = sum(1 for r in rr if r['site'] == 'site04_roi3')
    if hp:
        v = [h for h in hp if h['valid'] and h['predicted'] != 'outside']
        agree = sum(1 for h in v if h['observed'] == h['predicted'])
        w(f'{n04} scored held-out rows of Site04 RoI 3; the hero point is inside the image in {len(hp)}, valid in {len(v)}. '
          f'Agreement at the point (Otsu observed class vs PGDA 78 predicted, registered): **{agree}/{len(v)}**. One ≈ 5 m pixel '
          'per image; descriptive, not a validation of the point.\n')
        w('| product id | start UTC | Sun el ° | observed | predicted | to predicted edge m | image shadow IoU |\n|---|---|---|---|---|---|---|')
        for h in sorted(hp, key=lambda h: h['product_id']):
            w(f"| {h['product_id']} | {h.get('obs_utc') or '—'} | {fmt(h['sunEl'], 2)} | {h['observed']} | {h['predicted']} | "
              f"{fmt(h['predEdgeDistM'], 1)} | {fmt(h['iou'])} |")
    elif n04 == 0:
        w('No held-out Site04 RoI 3 row was scored.')
    # gallery (local only)
    w('\n## 10. Gallery (local only)\n')
    byk = {(r['product_id'], r['site']): r for r in rr}
    ks = sorted(byk)
    rng = np.random.default_rng(int(hashlib.sha256(b'polaris-x-v2-gallery').hexdigest(), 16) % 2 ** 63)
    rand = [ks[i] for i in sorted(rng.choice(len(ks), size=min(12, len(ks)), replace=False))] if ks else []
    worst = sorted(ks, key=lambda k: byk[k]['iouShadow'])[:max(1, math.ceil(0.1 * len(ks)))] if ks else []
    w('The random 12 (seed `polaris-x-v2-gallery`) and the worst 10 % by shadow IoU are listed here. Their thumbnails are '
      'crops of NASA LROC NAC images, so they are **not in git**; `--gallery` writes them to '
      '`docs/validation/render_vs_real_heldout/` locally.\n')
    w('| set | product id | site | shadow IoU | edge median m | pred / obs shadow frac | offset m |\n|---|---|---|---|---|---|---|')
    for name, kk in (('random', rand), ('worst 10 %', worst)):
        for k in kk:
            r = byk[k]
            w(f"| {name} | {k[0]} | {k[1]} | {fmt(r['iouShadow'])} | {fmt(r['edgeMedianM'], 1)} | {fmt(r['predShadowFrac'], 2)} / "
              f"{fmt(r['obsShadowFrac'], 2)} | {fmt(r.get('regOffsetM'), 0)} |")
            if a.gallery and C.SPLIT == 'heldout':
                try:
                    thumb(k, r, out_dir=GAL)
                except Exception as e:
                    print('thumb failed', k, e)
    # gated and failed
    w('\n## 11. Gated and failed rows\n')
    w('| stage | product id | site | reason |\n|---|---|---|---|')
    for g in sorted(sel.get('gatedByMetadata', []), key=lambda g: (g['reason'], g['product_id'], g['site'])):
        w(f"| metadata (§2) | {g['product_id']} | {g['site']} | {g['reason']} |")
    for g in sorted((g for g in geo if g['status'] != 'ok'), key=lambda g: (g['product_id'], g['site'])):
        w(f"| geometry ({g['status']}) | {g['product_id']} | {g['site']} | {g['reason']} |")
    for k, why in sorted(gated_score.items()):
        w(f'| scoring (gated) | {k[0]} | {k[1]} | {why} |')
    for k in sorted({(r['product_id'], r['site']): r for r in failed}):
        r = next(x for x in failed if (x['product_id'], x['site']) == k)
        w(f"| render/score (failed) | {k[0]} | {k[1]} | {r.get('reason', '')[:160]} |")
    w('')
    out = Path(a.out) if a.out else DOC
    out.write_text('\n'.join(L) + '\n')
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
